import { motion, useScroll, useTransform } from "motion/react";
import { useRef } from "react";
import { cn } from "@/lib/utils";
import { OrbitingCircles } from "@/components/magicui/orbiting-circles";

function TextReveal({ children }) {
  const targetRef = useRef(null);
  const { scrollYProgress } = useScroll({
    target: targetRef,
    offset: ["start start", "end end"],
  });

  if (typeof children !== "string") {
    throw new Error("TextReveal: children must be a string");
  }

  const words = children.split(" ");

  return (
    <>
      <div
        ref={targetRef}
        className={cn("relative w-full h-[150vh] mt-54 justify-center")}
      >
        <div className="sticky top-1/2 translate-y-full mx-auto flex items-center justify-center z-0" aria-hidden="true">
          <div className="overflow-hidden w-full max-w-[90%] md:max-w-[500px] flex items-center justify-center">
            <OrbitingCircles iconSize={45} radius={130} speed={0.5}>
              <Icons.Figma />
              <Icons.openAI />
              <Icons.React />
              <Icons.GSAP />
              <Icons.TailwindCSS />
              <Icons.Notion />
            </OrbitingCircles>
            <OrbitingCircles iconSize={30} radius={80} speed={1} reverse>
              <Icons.gitHub />
              <Icons.VisualStudioCode />
              <Icons.HTML />
              <Icons.CSS />
              <Icons.JS />
            </OrbitingCircles>
          </div>
        </div>
        <div className="sticky top-1/2 -translate-y-1/2  flex items-center justify-center z-10">
          <div className="flex flex-wrap justify-center w-4/5 mx-auto text-center gap-x-2 gap-y-1 text-2xl text-neutral-100 bg-transparent backdrop-blur-[1px]">
            {words.map((word, i) => {
              const start = i / words.length;
              const end = start + 1 / words.length;
              const opacity = useTransform(
                scrollYProgress,
                [start, end],
                [0, 1]
              );
              return (
                <span key={i} className="relative">
                  <span className="absolute inset-0 text-neutral-500 opacity-10">
                    {word}
                  </span>
                  <motion.span style={{ opacity }}>{word}</motion.span>
                </span>
              );
            })}
          </div>
        </div>
      </div>
    </>
  );
}

